import assert from 'node:assert/strict';
import { createSaveStatus } from '../js/core/itinerary-save-status.js';
let online = true;
let state;
const status = createSaveStatus(value => { state = value; }, () => online);
let complete;
const write = status.track(() => new Promise(resolve => { complete = resolve; }));
assert.equal(state, 'saving');
online = false;
status.refresh();
assert.equal(state, 'pending');
online = true;
status.refresh();
assert.equal(state, 'saving', 'Connectivity does not acknowledge writes');
complete();
await write;
assert.equal(state, 'saved');
let fail;
let succeed;
const first = status.track(() => new Promise((_, reject) => { fail = reject; }));
const rejection = assert.rejects(first, /denied/);
const second = status.track(() => new Promise(resolve => { succeed = resolve; }));
fail(new Error('denied'));
await rejection;
assert.equal(state, 'saving');
succeed();
await second;
assert.equal(state, 'error', 'Concurrent success must not hide failed writes');
await status.track(async () => true);
assert.equal(state, 'saved');
console.log('itinerary save status: ok');
