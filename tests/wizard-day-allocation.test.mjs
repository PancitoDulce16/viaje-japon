import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { DayAllocationBar } from '../js/features/itinerary/day-allocation-bar.js';
const source = fs.readFileSync(new URL('../js/features/itinerary/smart-generator-wizard.js', import.meta.url), 'utf8');
const context = { window: {}, console: { log() {} }, DayAllocationBar: { refresh() {} } };
vm.createContext(context);
vm.runInContext(source.replace(/^import .*;$/gm, '').replace('export const SmartGeneratorWizard', 'const SmartGeneratorWizard').replace('export default SmartGeneratorWizard;', ''), context);
const wizard = context.window.SmartGeneratorWizard;
wizard.saveToSessionStorage = () => {};
wizard.renderWizard = () => {};
wizard.wizardData = { totalDays: 10, cities: ['Tokyo', 'Kyoto', 'Nara'], cityStops: [{ city: 'Tokyo', days: 5 }, { city: 'Kyoto', days: 4 }, { city: 'Nara', days: 1 }] };
wizard.setCityStopDayTrip(2, true);
assert.deepEqual(Array.from(wizard.wizardData.cityStops, s => s.days), [5, 4, 1]);
wizard.setCityStopDayTrip(2, false);
assert.deepEqual(Array.from(wizard.wizardData.cityStops, s => s.days), [5, 4, 1]);
globalThis.window = { SmartGeneratorWizard: wizard };
DayAllocationBar.refresh = () => {};
DayAllocationBar.nudgeSegmentDays(2, 1);
assert.deepEqual(Array.from(wizard.wizardData.cityStops, s => s.days), [5, 4, 2]);
wizard.setDayAllocationMode('auto');
wizard.setDayAllocationMode('manual');
assert.deepEqual(Array.from(wizard.wizardData.cityStops, s => s.days), [5, 4, 2]);
wizard.validateField = () => true;
wizard.step1Phase = 'map';
wizard.goToStep1Phase('days');
assert.deepEqual(Array.from(wizard.wizardData.cityStops, s => s.days), [5, 4, 2]);
const before = JSON.stringify(wizard.wizardData);
wizard.addSuggestedDayTrip('Osaka', 'Kobe');
assert.equal(JSON.stringify(wizard.wizardData), before);
wizard.currentStep = 1;
wizard.saveStep1Data = () => {};
wizard.wizardData.travelerAges = [];
assert.equal(wizard.validateCurrentStep(), false, 'unbalanced allocation must be blocked');
DayAllocationBar.nudgeSegmentDays(2, -1);
assert.equal(wizard.validateCurrentStep(), true, 'balanced allocation can proceed');
DayAllocationBar.nudgeSegmentDays(2, -1);
assert.equal(wizard.wizardData.cityStops[2].days, 1, 'one day minimum');
wizard.wizardData.cityStops.push({ city: 'Osaka', days: null });
wizard.step1Phase = 'map';
wizard.goToStep1Phase('days');
assert.deepEqual(Array.from(wizard.wizardData.cityStops, s => s.days), [5, 4, 1, 1]);
wizard.wizardData.cityStops[0].isDayTrip = true;
assert.equal(wizard.validateCurrentStep(), false);
wizard.setCityStopDayTrip(0, false);
assert.equal(wizard.wizardData.cityStops[0].isDayTrip, false, 'a moved excursion can be restored as the first base');
const bar = { querySelectorAll: () => [] };
let sortableOptions;
globalThis.document = { getElementById: () => bar };
window.Sortable = class { constructor(_element, options) { sortableOptions = options; } };
let moved;
wizard.reorderCityStops = (from, to) => { moved = [from, to]; };
DayAllocationBar.attachHandlers();
sortableOptions.onEnd({ oldIndex: 4, newIndex: 0, oldDraggableIndex: 2, newDraggableIndex: 0 });
assert.deepEqual(moved, [2, 0], 'dividers must not count as city indexes');
console.log('wizard day allocation regressions: ok');
